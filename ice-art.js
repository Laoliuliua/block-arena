  const sprites = new Map();

  function getSprite(type) {
    if (sprites.has(type)) return sprites.get(type);
    if (!Object.prototype.hasOwnProperty.call(textures, type)) return null;
    const {colors, rows} = textures[type];
    const canvas = document.createElement('canvas');
    canvas.width = canvas.height = 16;
    const ctx = canvas.getContext('2d');
    rows.forEach((row, y) => {
      for (let x = 0; x < row.length; x++) {
        const index = parseInt(row[x], 36);
        if (!index) continue;
        ctx.fillStyle = colors[index - 1];
        ctx.fillRect(x, y, 1, 1);
      }
    });
    sprites.set(type, canvas);
    return canvas;
  }

  function drawItem(ctx, type, x, y, size = 28, angle = 0) {
    const sprite = getSprite(type);
    if (!sprite) return false;
    ctx.save();
    ctx.translate(x, y);
    ctx.rotate(angle);
    ctx.imageSmoothingEnabled = false;
    ctx.drawImage(sprite, -size / 2, -size / 2, size, size);
    ctx.restore();
    return true;
  }

  root.ArenaIceArt = {getSprite, drawItem};
